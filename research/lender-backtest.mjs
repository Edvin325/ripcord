#!/usr/bin/env node
// What would lending against Bitcoin with no liquidations have done, across all of
// Bitcoin's history? This replays every possible start day.
//
// A Ripcord lender's result depends only on the price at the end of the term, because
// nothing can happen before that. The rule modelled here is the rational borrower: repay
// if the Bitcoin is worth more than the debt, otherwise walk away and leave the lender the
// coins. That is the lender's worst case, so these numbers are conservative for lenders.
//
// It also counts how many of the same loans a price-triggered lender would have liquidated
// on the way, even though Bitcoin was above the debt again by the due date.
//
// Data: daily average USD price from blockchain.com, saved in btc-daily-usd.csv so this
// reruns offline. Daily averages hide intraday wicks, which understates how often a
// price-triggered loan is really liquidated.
//
//   node lender-backtest.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const rows = readFileSync(new URL('btc-daily-usd.csv', here), 'utf8').trim().split('\n').slice(1);
const history = rows.map((r) => {
  const [date, price] = r.split(',');
  return { date, price: Number(price) };
});

const LTVS = [30, 40, 50, 60, 70];
const TERMS = [7, 30, 90];

// A round figure for the kind of lending market this replaces. It is an assumption, so
// change it and rerun to see the effect.
const LIQUIDATION_LTV = 0.8;

function run(days, ltvPercent, term, apr = 0) {
  const ltv = ltvPercent / 100;
  const debtFactor = ltv * (1 + (apr * term) / 365);
  let loans = 0;
  let defaults = 0;
  let totalLoss = 0;
  let worstLoss = 0;
  let worstDate = '';
  let liquidated = 0;
  let needlesslyLiquidated = 0;

  for (let i = 0; i + term < days.length; i++) {
    const start = days[i].price;
    const end = days[i + term].price;
    const debtPrice = start * debtFactor; // the price at which the coins equal the debt
    const principal = start * ltv;
    loans += 1;

    const defaulted = end < debtPrice;
    if (defaulted) {
      defaults += 1;
      const loss = Math.max(0, 1 - end / principal);
      totalLoss += loss;
      if (loss > worstLoss) {
        worstLoss = loss;
        worstDate = days[i].date;
      }
    }

    // A price-triggered lender sells once the loan reaches its liquidation LTV.
    const trigger = (start * ltv) / LIQUIDATION_LTV;
    let touched = false;
    for (let k = i + 1; k <= i + term; k++) {
      if (days[k].price <= trigger) {
        touched = true;
        break;
      }
    }
    if (touched) {
      liquidated += 1;
      if (!defaulted) needlesslyLiquidated += 1;
    }
  }

  const expectedLoss = totalLoss / loans;
  return {
    loans,
    defaultRate: defaults / loans,
    expectedLoss,
    worstLoss,
    worstDate,
    breakEvenApr: expectedLoss * (365 / term),
    liquidationRate: liquidated / loans,
    needlessRate: needlesslyLiquidated / loans,
  };
}

const pct = (x, digits = 2) => `${(x * 100).toFixed(digits)}%`;

function table(title, days) {
  const lines = [
    `### ${title}`,
    '',
    `${days.length.toLocaleString('en-US')} days, ${days[0].date} to ${days[days.length - 1].date}.`,
    '',
    '| LTV | Term | Ends underwater | Expected loss | Worst loss | Break-even APR | Hit a price trigger | Hit it, yet recovered |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const term of TERMS) {
    for (const ltv of LTVS) {
      const r = run(days, ltv, term);
      lines.push(
        `| ${ltv}% | ${term}d | ${pct(r.defaultRate)} | ${pct(r.expectedLoss, 3)} | ${r.worstLoss ? `${pct(r.worstLoss, 1)} (${r.worstDate})` : 'none'} | ${pct(r.breakEvenApr)} | ${pct(r.liquidationRate)} | ${pct(r.needlessRate)} |`,
      );
    }
  }
  return lines.join('\n');
}

const all = history.filter((d) => d.date >= '2013-01-01');
const recent = history.filter((d) => d.date >= '2021-01-01');

const report = `# Lender backtest

Generated by \`lender-backtest.mjs\` from \`btc-daily-usd.csv\`. Rerun it to reproduce every number.

Each row replays a loan from every possible start day. A loan is "underwater" if, on the due date, Bitcoin is worth less than the debt. The model assumes the borrower then walks away, which is the lender's worst case.

- **Expected loss** is the average principal lost, across all start days.
- **Break-even APR** is the rate that would have exactly covered that loss. A lender needs to charge more than this.
- **Hit a price trigger** is the share of all these loans that would have reached a ${LIQUIDATION_LTV * 100}% liquidation LTV at any point in the term. That figure is an assumption, set at the top of the script.
- **Hit it, yet recovered** is the share of all these loans that reached the trigger and were above the debt again by the due date. Those borrowers would lose their position on a price-triggered platform and keep it on Ripcord.

These are daily averages, so intraday wicks are missing, which understates price-triggered liquidations. Past prices do not predict future ones. Interest is not counted towards the debt here, which makes the underwater figures slightly lower than a real loan's.

${table('All of it since 2013', all)}

${table('Since 2021', recent)}
`;

writeFileSync(new URL('lender-backtest.md', here), report);
console.log(report);
